const DICTIONARIES = { de };
let current = 'en';

/** 'auto' (or anything unknown) = the browser's language when there is a translation for it, else English. */
export function resolveLanguage(choice) {
  if (Object.hasOwn(LANGUAGES, choice)) return choice;
  for (const tag of navigator.languages ?? [navigator.language ?? 'en']) {
    const code = String(tag).slice(0, 2).toLowerCase();
    if (Object.hasOwn(LANGUAGES, code)) return code;
  }
  return 'en';
}

/** Returns true when the language changed. */
export function setLanguage(choice) {
  const next = resolveLanguage(choice);
  const changed = next !== current;
  current = next;
  document.documentElement.lang = next;
  return changed;
}

export const language = () => current;

/** True when the current language has its own text for this English one. */
export const hasText = (text) => current !== 'en' && Object.hasOwn(DICTIONARIES[current] ?? {}, text);

export function t(text, vars) {
  const dict = DICTIONARIES[current];
  let out = dict && Object.hasOwn(dict, text) ? dict[text] : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
